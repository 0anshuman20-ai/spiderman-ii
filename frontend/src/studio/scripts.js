/* SPACESPIDEY — SCRIPT LIBRARY (46 signals) — DEFINITIVE SIMPLE EDITION

   THE ONE LAW: every spoken word must be a word a 10-year-old uses.
   If a kid would ask "what does that mean?", the line is wrong. Rewrite it.

   The 21-second shape (built from real retention data):

     0.0-0.7s  ONE moving image + up to 4 big simple words on screen.
               The words open a question. They never name a topic.
     0.7-3s    Spoken hook. 7 words or fewer. It says the scary or
               impossible part FIRST. Never a greeting. Never setup.
     3-6s      The fact, in one short sentence. Words a kid knows.
     6-9s      A tiny new question, so nobody leaves in the middle.
     9-13s     THE TURN. The "wait, WHAT" moment. Never save it for the end.
     13-17s    The payoff. It answers the big words from the first frame.
     17-21s    One story line, clearly a story. Then loop back to the start.

   Word rules (never break these):
     - Short sentences. 8 words or fewer is the goal.
     - Only words a 10-year-old says out loud. "Big" not "enormous".
       "For sure" not "confirmed". "Aliens" not "civilisations".
     - One idea per sentence. Never two.
     - Real numbers, said simply: "8 minutes", "1 spoon", "15 seconds".
     - No "basically", no "in this video", no begging for likes.
     - Say "you" and "your" as much as possible. The video is about them.

   Three rules the whole library obeys:
     1. If a 10-year-old cannot say the fact back to you, rewrite it.
     2. Real science and the story never mix. Story is last, and labelled.
     3. No script can promise views. Test, keep winners, delete losers.   */

